import ucdef


def genera_manual_2(uc_firefox, uc_chrome, win_10, win_11):
    entradas = []
    incluidos = set()

    def agrega(cadena, mensajes):
        if cadena in incluidos:
            return
        incluidos.add(cadena)
        codigos = [codigo.replace("U+", "") for codigo in cadena.split()]
        entradas.append([codigos, mensajes])

    for cadena in uc_firefox:
        agrega(cadena, ["No disponible en Firefox"])
    for cadena in uc_chrome:
        agrega(cadena, ["No disponible en Chrome"])
    for cadena in win_10:
        mensajes = ["No disponible en Windows 10"]
        if cadena in win_11:
            mensajes.append("No disponible en Windows 11")
        agrega(cadena, mensajes)
    for cadena in win_11:
        if cadena not in win_10:
            agrega(cadena, ["No disponible en Windows 11"])
    return entradas


